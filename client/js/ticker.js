const xarcanoid_ticker = (() => {
    let track = null;
    let text_el = null;
    let get_ctx = null;
    let offset = 0;
    let last_line = "";
    let running = false;
    let last_ts = 0;
    const speed = 72;

    function collect(ctx) {
        const lang = ctx.lang === "en" ? "en" : "ru";
        const pack = xarcanoid_ticker_lines[lang];
        const pool = pack.generic.slice();
        const add = (key) => {
            const list = pack[key];
            if (list && list.length) {
                pool.push.apply(pool, list);
            }
        };
        add(ctx.difficulty);
        add(ctx.mode);
        if (ctx.boss) {
            add("boss" + Math.max(1, Math.min(3, ctx.boss_phase || 1)));
        }
        add(ctx.music ? "music_on" : "music_off");
        add(ctx.sfx ? "sfx_on" : "sfx_off");
        add(ctx.theme);
        add(lang === "en" ? "lang_en" : "lang_ru");
        if (ctx.rank === 1) {
            add("rank_top");
        } else if (ctx.rank && ctx.rank <= 5) {
            add("rank_mid");
        } else if (ctx.rank) {
            add("rank_low");
        }
        add("eggs");
        return pool;
    }

    function pick() {
        const ctx = get_ctx ? get_ctx() : { lang: "ru" };
        const pool = collect(ctx);
        if (!pool.length) {
            return "";
        }
        let line = last_line;
        let guard = 0;
        while (line === last_line && guard < 8) {
            line = pool[Math.floor(Math.random() * pool.length)];
            guard += 1;
        }
        last_line = line;
        return line;
    }

    function load_line() {
        if (!text_el || !track) {
            return;
        }
        text_el.textContent = pick();
        offset = track.clientWidth;
        text_el.style.transform = "translateX(" + offset + "px)";
    }

    function tick(ts) {
        if (!running) {
            return;
        }
        const dt = last_ts ? Math.min(0.05, (ts - last_ts) / 1000) : 0;
        last_ts = ts;
        offset -= speed * dt;
        const width = text_el ? text_el.offsetWidth : 0;
        if (offset < -width - 24) {
            load_line();
        } else if (text_el) {
            text_el.style.transform = "translateX(" + offset + "px)";
        }
        requestAnimationFrame(tick);
    }

    function start(track_node, text_node, ctx_fn) {
        track = track_node;
        text_el = text_node;
        get_ctx = ctx_fn;
        running = true;
        last_ts = 0;
        load_line();
        requestAnimationFrame(tick);
    }

    function refresh() {
        if (running) {
            load_line();
        }
    }

    return { start, refresh };
})();
